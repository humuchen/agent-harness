const test = require('node:test');
const assert = require('node:assert');

const {
  dialectFromUrl,
  translateDdl,
  translateStatement,
  translateSqlFor,
  pgParams,
  isPragma,
  listTablesSql,
  tableColumnsSql,
  getDbAdapter,
  resetDbAdaptersForTest,
} = require('../dist/index.js');

// ---------------------------------------------------------------------------
// dialectFromUrl
// ---------------------------------------------------------------------------

test('dialectFromUrl：scheme 识别与归一', () => {
  assert.strictEqual(dialectFromUrl('mysql://u:p@h:3306/db'), 'mysql');
  assert.strictEqual(dialectFromUrl('mariadb://u@h/db'), 'mysql');
  assert.strictEqual(dialectFromUrl('postgres://u@h/db'), 'postgres');
  assert.strictEqual(dialectFromUrl('postgresql://u@h/db'), 'postgres');
  assert.strictEqual(dialectFromUrl('file:./x.db'), null);
  assert.strictEqual(dialectFromUrl('libsql://x.turso.io'), null);
  assert.strictEqual(dialectFromUrl(''), null);
});

// ---------------------------------------------------------------------------
// DDL 翻译
// ---------------------------------------------------------------------------

const SAMPLE_DDL =
  'CREATE TABLE IF NOT EXISTS accounts (' +
  'id TEXT PRIMARY KEY, name TEXT, score REAL, n INTEGER PRIMARY KEY AUTOINCREMENT, created DATETIME)';

test('translateDdl(mysql)：TEXT 主键→VARCHAR(255)、AUTOINCREMENT、REAL→DOUBLE', () => {
  const out = translateDdl(SAMPLE_DDL, 'mysql');
  assert.match(out, /id VARCHAR\(255\) PRIMARY KEY/);
  assert.match(out, /name TEXT(?!\s+PRIMARY)/, '普通 TEXT 列保留');
  assert.match(out, /n INT AUTO_INCREMENT PRIMARY KEY/);
  assert.match(out, /score DOUBLE/);
});

test('translateDdl(postgres)：identity 列、TEXT 主键保留', () => {
  const out = translateDdl(SAMPLE_DDL, 'postgres');
  assert.match(out, /id TEXT PRIMARY KEY/);
  assert.match(out, /n INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
});

test('translateDdl：datetime(\'now\') 按方言替换', () => {
  const sql = "CREATE TABLE t (ts DATETIME DEFAULT datetime('now'))";
  assert.match(translateDdl(sql, 'mysql'), /DEFAULT CURRENT_TIMESTAMP/);
  assert.match(translateDdl(sql, 'postgres'), /DEFAULT now\(\)/);
  assert.match(translateDdl(sql, 'sqlite'), /datetime\('now'\)/, 'sqlite 原样');
});

test('translateDdl：BLOB → PG BYTEA', () => {
  assert.match(translateDdl('CREATE TABLE t (b BLOB)', 'postgres'), /BYTEA/);
});

// ---------------------------------------------------------------------------
// DML 翻译
