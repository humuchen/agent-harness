test('isPragma 与 splitSqlStatements', () => {
  assert.strictEqual(isPragma('PRAGMA journal_mode=WAL'), true);
  assert.strictEqual(isPragma('SELECT 1'), false);
});

test('listTablesSql / tableColumnsSql：三方言统一 name 列', () => {
  for (const d of ['sqlite', 'mysql', 'postgres']) {
    const t = listTablesSql(d);
    assert.match(t.sql, /AS name/i, `${d} 表发现应含 name 别名`);
    const c = tableColumnsSql(d, 't1');
    if (d === 'sqlite') {
      assert.match(c.sql, /^PRAGMA table_info/i, 'sqlite 列信息走 PRAGMA');
    } else {
      assert.match(c.sql, /AS name/i, `${d} 列信息应含 name 别名`);
    }
  }
});

test('getDbAdapter：mysql/postgres 配置缺失或不匹配时 fail-fast', () => {
  resetDbAdaptersForTest();
  const oldBackend = process.env.DB_BACKEND;
  const oldUrl = process.env.DATABASE_URL;
  try {
    delete process.env.DATABASE_URL;
    assert.throws(() => getDbAdapter({ backend: 'mysql' }), /DATABASE_URL/);
    assert.throws(() => getDbAdapter({ backend: 'postgres' }), /DATABASE_URL/);
    // scheme 不匹配同样 fail-fast（数据落错库比启动失败更难收拾）
    assert.throws(
      () => getDbAdapter({ backend: 'mysql', url: 'postgres://u@h/db' }),
      /DATABASE_URL/
    );
  } finally {
    if (oldBackend === undefined) delete process.env.DB_BACKEND;
    else process.env.DB_BACKEND = oldBackend;
    if (oldUrl === undefined) delete process.env.DATABASE_URL;
    else process.env.DATABASE_URL = oldUrl;
    resetDbAdaptersForTest();
  }
});

test('getDbAdapter：合法 DATABASE_URL 惰性建连（无需真实服务）+ 单例', () => {
  resetDbAdaptersForTest();
  const oldBackend = process.env.DB_BACKEND;
  const oldUrl = process.env.DATABASE_URL;
  try {
    const a = getDbAdapter({ backend: 'mysql', url: 'mysql://u:p@127.0.0.1:3306/nope' });
    const b = getDbAdapter({ backend: 'mysql', url: 'mysql://u:p@127.0.0.1:3306/nope' });
    assert.strictEqual(a, b, '同 URL 单例');
    assert.strictEqual(a.cacheKey.startsWith('mysql:'), true);
    const p = getDbAdapter({ backend: 'postgres', url: 'postgres://u:p@127.0.0.1:5432/nope' });
    assert.strictEqual(p.cacheKey.startsWith('postgres:'), true);
    // PG prepare 的 ?→$n 在语句级生效（不触发连接）
    const stmt = p.prepare('SELECT * FROM t WHERE a = ?');
    assert.ok(typeof stmt.all === 'function');
  } finally {
    if (oldBackend === undefined) delete process.env.DB_BACKEND;
    else process.env.DB_BACKEND = oldBackend;
    if (oldUrl === undefined) delete process.env.DATABASE_URL;
    else process.env.DATABASE_URL = oldUrl;
    resetDbAdaptersForTest();
  }
});

