test('translateStatement(mysql)：INSERT OR IGNORE → INSERT IGNORE', () => {
  const out = translateStatement("INSERT OR IGNORE INTO t (a) VALUES (?)", 'mysql');
  assert.match(out, /INSERT IGNORE INTO t/);
});

test('translateStatement(mysql)：ON CONFLICT DO UPDATE → ON DUPLICATE KEY UPDATE + VALUES(col)', () => {
  const out = translateStatement(
    'INSERT INTO tenant_quotas (tenant_id, qps) VALUES (?, ?) ON CONFLICT(tenant_id) DO UPDATE SET qps=excluded.qps, updated_at=excluded.updated_at',
    'mysql'
  );
  assert.match(out, /ON DUPLICATE KEY UPDATE/);
  assert.match(out, /qps=VALUES\(qps\)/);
  assert.match(out, /updated_at=VALUES\(updated_at\)/);
  assert.doesNotMatch(out, /excluded\./);
});

test('translateStatement(postgres)：INSERT OR IGNORE 追加 ON CONFLICT DO NOTHING', () => {
  const out = translateStatement('INSERT OR IGNORE INTO t (a) VALUES (?)', 'postgres');
  assert.match(out, /^INSERT INTO t \(a\) VALUES \(\?\) ON CONFLICT DO NOTHING$/);
  // 显式 upsert 不重复追加
  const out2 = translateStatement(
    'INSERT INTO q (id, v) VALUES (?, ?) ON CONFLICT(id) DO UPDATE SET v=excluded.v',
    'postgres'
  );
  assert.strictEqual((out2.match(/ON CONFLICT/g) || []).length, 1, '已有 ON CONFLICT 不重复追加');
});

test('pgParams：? 顺序编号，单引号字面量内跳过', () => {
  assert.strictEqual(pgParams('a = ? AND b = ?'), 'a = $1 AND b = $2');
  assert.strictEqual(pgParams("msg = 'what?' AND a = ?"), "msg = 'what?' AND a = $1");
});

test('translateSqlFor：一站式（PG 含占位符，MySQL 不改占位符）', () => {
  assert.strictEqual(translateSqlFor('a=?', 'postgres', true), 'a=$1');
  assert.strictEqual(translateSqlFor('a=?', 'mysql', true), 'a=?');
});

